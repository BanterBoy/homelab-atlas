import { readFile, readdir, writeFile } from 'node:fs/promises';
import { basename, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const logoDir = resolve(root, 'public/logos');
const output = resolve(root, 'public/icon-data.js');
const unsafe = /<!DOCTYPE|<!ENTITY|<script\b|<foreignObject\b|<iframe\b|<object\b|<embed\b|\s+on[a-z]+\s*=|\b(?:href|src)\s*=\s*["'](?!#)/i;

const files = (await readdir(logoDir)).filter(name => name.endsWith('.svg')).sort();
const icons = {};

for (const file of files) {
  const svg = await readFile(resolve(logoDir, file), 'utf8');
  const root = svg.trimStart().replace(/^<\?xml[^>]*>\s*/i, '');
  if (!root.startsWith('<svg') || unsafe.test(svg)) {
    throw new Error(`Unsafe SVG: ${file}`);
  }
  icons[basename(file, '.svg')] = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
}

const source = `// Generated by npm run build:icons. Do not edit.\nexport const ICON_DATA=Object.freeze(${JSON.stringify(icons)});\n`;
await writeFile(output, source);
console.log(`Generated ${files.length} embedded icons.`);
